import Pocketbase from 'pocketbase';
import { mkdirSync, writeFileSync } from 'fs';
import { dirname } from 'node:path';

const url = process.env.VITE_POCKETBASE_URL
const email = process.env.PB_ADMIN_EMAIL
const password = process.env.PB_ADMIN_PASSWORD
const outFile = 'src/types/pocketbase-models.ts'

if (!url || !email || !password) {
  console.error('VITE_POCKETBASE_URL, VITE_POCKETBASE_EMAIL, and VITE_POCKETBASE_PASSWORD must be defined in the environment variables');
  process.exit(1);
}

const pb = new Pocketbase(url);

await pb.collection('_superusers').authWithPassword(email, password);

const collections = (await pb.collections.getFullList({ sort: 'name'}))
  .filter((c) => !c.name.startsWith('_'));

const pascal = (str) => 
  str.split(/[-_]/).map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join('');

function tsType(field) {
  switch (field.type) {
    case 'number':
      return 'number'
    case 'bool':
      return 'boolean'
    case 'json':
      return 'unknown'
    case 'geoPoint':
      return '{ lon: number; lat: number }'
    case 'select':
    case 'relation':
    case 'file':
      return field.maxSelect > 1 ? 'string[]' : 'string'
    default:
      return 'string'
  }
}

let out = `// This file is auto-generated by scripts/generate-models.mjs
// Do not edit this file directly, as your changes will be overwritten.

`;

const recordNames = []

for (const col of collections) {
  const name = pascal(col.name) + 'Record'
  recordNames.push({ collection: col.name, name })

  const fields = col.fields.filter((f) => f.type !== 'password')

  out += `export interface ${name} {\n`
  for (const f of fields) {
    const optional = f.required ? '' : '?'
    out += `  ${f.name}${optional}: ${tsType(f)}\n`
  }
  out += `}\n\n`
}

out += `export interface CollectionRecords {\n`
for (const r of recordNames) {
  out += `  '${r.collection}': ${r.name}\n`
}
out += `}\n\n`

out += `export type CollectionName = keyof CollectionRecords\n`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, out)

console.log(`✔ ${collections.length} collections exported to ${outFile}`)
